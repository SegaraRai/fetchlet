// Writes the native APIs each engine provides, as `vp run test:polyfills`
// measured them into results/polyfill-matrix.json, to the table
// fetchlet/build plans from: `vp run build:engine-capabilities`. With --check
// it fails instead of writing when the table differs from the results, which
// `vp run check` runs.

import { readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { root } from "@fetchlet-internal/tools-workspace/paths";

const input = resolve(root, "results/polyfill-matrix.json");
const output = resolve(root, "packages/fetchlet/src/build/polyfills/engine-capabilities.ts");
// The formatter's line width, so the written file passes `vp fmt --check`.
const printWidth = 100;

const measured = JSON.parse(readFileSync(input, "utf8")).nativeCapabilities as Record<
  string,
  Record<string, boolean>
>;

function entry(name: string, apis: string[]): string[] {
  const line = `  ${name}: [${apis.map((api) => JSON.stringify(api)).join(", ")}],`;
  if (line.length <= printWidth || apis.length === 0) {
    return [line];
  }
  return [`  ${name}: [`, ...apis.map((api) => `    ${JSON.stringify(api)},`), "  ],"];
}

const table: [string, string[]][] = [
  ["portable", []],
  ...Object.entries(measured).map(([backend, apis]): [string, string[]] => [
    backend,
    Object.entries(apis)
      .filter(([, native]) => native)
      .map(([api]) => api),
  ]),
];

const text = [
  "// Generated by tools/matrix/engine-capabilities.ts from results/polyfill-matrix.json.",
  "// Run `vp run test:polyfills` and then `vp run build:engine-capabilities`.",
  "",
  'import type { BuildBackend } from "./plan.ts";',
  "",
  "/**",
  " * Native APIs measured in fetchlet's default engine configurations, by their",
  " * path from `globalThis`. `portable` assumes none.",
  " */",
  "export const backendCapabilities: Record<BuildBackend, string[]> = {",
  ...table.flatMap(([backend, apis]) => entry(backend, apis)),
  "};",
  "",
].join("\n");

if (process.argv.includes("--check")) {
  const committed = readFileSync(output, "utf8").replaceAll("\r\n", "\n");
  if (committed !== text) {
    console.error(
      "[engine-capabilities] " +
        output +
        " differs from results/polyfill-matrix.json; run `vp run build:engine-capabilities`",
    );
    process.exit(1);
  }
} else {
  writeFileSync(output, text);
}
