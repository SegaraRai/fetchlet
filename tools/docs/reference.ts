function fuzzing(): string[] {
  const result = read("fuzz-smoke.json");
  const rows = (result.targets as { target: string; status: string; completedRuns: number }[]).map(
    (target) => [target.target, target.status, target.completedRuns.toLocaleString("en-US")],
  );
  return [
    "## Fuzzing",
    "",
    `\`vp run test:fuzz\`, ${date(result.checkedAt)}. AddressSanitizer, up to ${result.requestedRuns.toLocaleString("en-US")} runs or ${result.timeBudgetSeconds} s per target, ${result.compiler}.`,
    "",
    ...table(["Target", "Status", "Runs"], rows),
  ];
}

function aot(): string[] {
  const matrix = read("aot-matrix.json");
  const link = read("native-link-matrix.json");
  const matrixRows = (
    matrix.results as {
      backend: string;
      compiler: string;
      suite: string;
      inputMode: string;
      status: string;
    }[]
  ).map((entry) => [
    `${entry.backend} ${entry.compiler}`,
    entry.suite,
    entry.inputMode,
    entry.status,
  ]);
  const linkRows = (link.results as { backend: string; stage: string; status: string }[]).map(
    (entry) => [entry.backend, entry.stage, entry.status],
  );
  return [
    "## Ahead-of-time compilation",
    "",
    `\`vp run test:aot\`, ${date(matrix.checkedAt)}. Experimental; [research](../research/native-aot.md) explains the failures.`,
    "",
    ...table(["Compiler", "Suite", "Input", "Status"], matrixRows),
    "",
    `\`vp run test:aot-link\`, ${date(link.checkedAt)}, target ${link.target}.`,
    "",
    ...table(["Compiler", "Stage", "Status"], linkRows),
  ];
}

function benchmarks(): string[] {
  const result = read("bench.json");
  return [
    "## Benchmarks",
    "",
    `\`vp run bench\`, ${date(result.measuredAt)}, on ${result.machine.cpu}. Requests per second and latency per example and engine are in [results/bench.md](../../results/bench.md).`,
  ];
}

/** A result file; the files are plain JSON written by the test tools. */
function read(name: string): any {
  return JSON.parse(readFileSync(resolve(root, "results", name), "utf8"));
}

function ratio(entries: Outcome[]): string {
  const passed = entries.filter((entry) => entry.status === "pass").length;
  return `${passed} / ${entries.length}`;
}

function date(value: string): string {
  return value.slice(0, 10);
}

function short(revision: string): string {
  return revision.slice(0, 12);
}

function table(header: string[], rows: string[][]): string[] {
  const widths = header.map((cell, column) =>
    Math.max(cell.length, ...rows.map((row) => (row[column] ?? "").length)),
  );
  const line = (cells: string[]) =>
    `| ${cells.map((cell, column) => cell.padEnd(widths[column] ?? 0)).join(" | ")} |`;
  return [
    line(header),
    `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`,
    ...rows.map(line),
  ];
}
