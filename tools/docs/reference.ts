/**
 * Features per example: covered by a passing check, failing, unsupported by
 * design (declared in tools/examples/features.ts with a reason) or untested.
 */
function frameworkFeatures(): string[] {
  const names = exampleNames();
  const notes: string[] = [];
  const results = names.map(
    (name) => read(`example-${name}.json`).results as { features?: Feature[]; status: string }[],
  );
  const rows = (Object.keys(features) as Feature[]).map((feature) => [
    features[feature],
    ...names.map((name, index) => {
      const covering = (results[index] ?? []).filter((row) => row.features?.includes(feature));
      const reason = unsupported[name]?.[feature];
      if (reason) {
        if (covering.length)
          throw new Error(`${name} declares ${feature} unsupported but checks it`);
        if (!notes.includes(reason)) notes.push(reason);
        return `n/a (${notes.indexOf(reason) + 1})`;
      }
      if (!covering.length) return "—";
      return covering.every((row) => row.status === "pass") ? "✓" : "✗";
    }),
  ]);
  const short = (name: string) => name.replace(/-axum/, "").replace("-tauri-desktop", " desktop");
  return [
    "## Framework features",
    "",
    "Features each example's checks cover: ✓ passed, ✗ failed, — not checked, n/a unsupported by design. The checks name their features; [features.ts](../../tools/examples/features.ts) declares what cannot apply.",
    "",
    ...table(["Feature", ...names.map(short)], rows),
    "",
    ...notes.map((reason, index) => `${index + 1}. ${reason}.`),
  ];
}

function examples(): string[] {
  const names = exampleNames();
  const passed = (file: string) => {
    if (!existsSync(resolve(root, "results", file))) {
      return "—";
    }
    const { summary } = read(file);
    return `${summary.passed} / ${summary.passed + summary.failed}`;
  };
  const rows = names.map((name) => {
    const result = read(`example-${name}.json`);
    return [
      name,
      passed(`example-${name}.json`),
      passed(`example-${name}-boa.json`),
      passed(`example-${name}-v8.json`),
      framework(result),
      result.browser ?? "—",
    ];
  });
  return [
    "## Examples",
    "",
    "`vp run test:examples` on QuickJS; `vp run test:examples -- --backends boa,v8` records the other engines. HTTP and browser checks per example; the feature table below shows the QuickJS run.",
    "",
    ...table(["Example", "QuickJS", "Boa", "V8", "Framework", "Browser"], rows),
  ];
}

function fuzzing(): string[] {
  const result = read("fuzz-smoke.json");
  const rows = (result.targets as { target: string; status: string }[]).map((target) => [
    target.target,
    target.status,
  ]);
  return [
    "## Fuzzing",
    "",
    `\`vp run test:fuzz\`. ${recorded(result)} AddressSanitizer, up to ${result.requestedRuns.toLocaleString("en-US")} runs or ${result.timeBudgetSeconds} s per target, ${result.compiler}.`,
    "",
    ...table(["Target", "Status"], rows),
  ];
}

/** A result file; the files are plain JSON written by the test tools. */
function read(name: string): any {
  return JSON.parse(readFileSync(resolve(root, "results", name), "utf8"));
}

function ratio(entries: Outcome[]): string {
  const passed = entries.filter((entry) => entry.status === "pass").length;
  return `${passed} / ${entries.length}`;
}

/** The versions a result records, as a sentence. */
function recorded(result: { environment?: Environment }): string {
  const environment = result.environment;
  if (!environment) return "The run predates version recording.";
  const engineList = Object.values(environment.engines).join(", ");
  return `Recorded with ${environment.rustc}, Node ${environment.node} on ${environment.platform}; ${engineList}.`;
}

function engineVersion(result: { environment?: Environment }, engine: string): string {
  if (engine === "node-reference") return result.environment?.node ?? "—";
  return result.environment?.engines[engine as keyof Environment["engines"]] ?? "—";
}

function framework(result: { environment?: Environment }): string {
  // Packages that name an example's framework, in order of preference.
  const frameworkPackages = [
    "@sveltejs/kit",
    "@solidjs/start",
    "@tanstack/react-start",
    "@builder.io/qwik-city",
    "@qwik.dev/router",
    "react-router",
    "astro",
    "honox",
    "nuxt",
    "vinext",
    "waku",
  ];
  const packages = result.environment?.packages ?? {};
  const name = frameworkPackages.find((candidate) => candidate in packages);
  return name ? `${name} ${packages[name]}` : "—";
}

function short(revision: string): string {
  return revision.slice(0, 12);
}

function table(header: string[], rows: string[][]): string[] {
  const widths = header.map((cell, column) =>
    Math.max(cell.length, ...rows.map((row) => (row[column] ?? "").length)),
  );
  const line = (cells: string[]) =>
    `| ${cells.map((cell, column) => cell.padEnd(widths[column] ?? 0)).join(" | ")} |`;
  return [
    line(header),
    `| ${widths.map((width) => "-".repeat(width)).join(" | ")} |`,
    ...rows.map(line),
  ];
}
