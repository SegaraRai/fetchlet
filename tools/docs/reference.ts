// Renders the recorded results in results/ into docs/reference/README.md:
// `vp run build:reference`. With --check it fails instead of writing when the
// page differs from what the results produce, which `vp run check` runs.

import { existsSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";

import { root } from "@fetchlet-internal/tools-workspace/paths";
import { features, unsupported, type Feature } from "@fetchlet-internal/tools-examples/features";
import type { Environment } from "@fetchlet-internal/tools-workspace/results";

const output = resolve(root, "docs/reference/README.md");
const engines = ["quickjs", "boa", "v8", "node-reference"];
const engineNames: Record<string, string> = {
  quickjs: "QuickJS",
  boa: "Boa",
  v8: "V8",
  "node-reference": "Node (reference)",
};

interface Outcome {
  status: string;
}

const sections = [
  engineMatrix(),
  webApiProbes(),
  hostServices(),
  conformance(),
  url(),
  polyfills(),
  examples(),
  frameworkFeatures(),
  fuzzing(),
];

const page = [
  "# Reference",
  "",
  "<!-- Generated by tools/docs/reference.ts from results/. Run `vp run build:reference` after recording results. -->",
  "",
  "Measured results, rendered from the JSON files in [results/](../../results/).",
  "Each section names the suite that records it; [verification](../verification.md)",
  "describes the suites. Each section names the versions its run recorded.",
  "",
  ...sections.flatMap((section) => [...section, ""]),
]
  .join("\n")
  .replace(/\n+$/, "\n");

if (process.argv.includes("--check")) {
  const current = existsSync(output) ? readFileSync(output, "utf8") : "";
  if (current.replaceAll("\r\n", "\n") !== page) {
    console.error(
      "[reference] docs/reference/README.md does not match results/; run `vp run build:reference`",
    );
    process.exit(1);
  }
  console.log("[reference] docs/reference/README.md matches results/");
} else {
  mkdirSync(dirname(output), { recursive: true });
  writeFileSync(output, page);
  console.log("[reference] wrote docs/reference/README.md");
}

function engineMatrix(): string[] {
  const result = read("runtime-matrix.json");
  const suites = ["functions", "hono", "sveltekit", "web-api"];
  const rows = engines.map((engine) => [
    engineNames[engine] ?? engine,
    ...suites.map((suite) =>
      ratio(
        result.results.filter(
          (entry: { backend: string; suite: string }) =>
            entry.backend === engine && entry.suite === suite,
        ),
      ),
    ),
  ]);
  return [
    "## Engine matrix",
    "",
    `\`vp run test:matrix\`. ${recorded(result)} Plain functions, Hono JSX and SvelteKit fixtures, and the Web API probe suite as one item.`,
    "",
    ...table(["Engine", "Functions", "Hono", "SvelteKit", "Web API probes"], rows),
  ];
}

function webApiProbes(): string[] {
  const rows = engines.map((engine) => {
    const result = read(`web-api-${engine}.json`);
    return [
      engineNames[engine] ?? engine,
      `${result.summary.passed} / ${result.summary.total}`,
      engineVersion(result, engine),
    ];
  });
  return [
    "## Web API probes",
    "",
    "`vp run test:matrix`. The behavior probes of [fixtures/probe](../../fixtures/probe/README.md).",
    "",
    ...table(["Engine", "Passed", "Engine version"], rows),
  ];
}

function hostServices(): string[] {
  const result = read("host-matrix.json");
  const rows = ["quickjs", "boa", "v8"].map((engine) => [
    engineNames[engine] ?? engine,
    ratio(result.results.filter((entry: { backend: string }) => entry.backend === engine)),
  ]);
  return [
    "## Host services",
    "",
    `\`vp run test:host\`. ${recorded(result)} JavaScript fetch through mock transports.`,
    "",
    ...table(["Engine", "Passed"], rows),
  ];
}

function conformance(): string[] {
  const result = read("conformance.json");
  const cell = (suite: string, engine: string) => {
    const counts = result.summary[`${suite}/${engine}`];
    if (!counts) return "—";
    const known = counts.expectedFailures ? ` (${counts.expectedFailures} known)` : "";
    return `${counts.pass} / ${counts.fail}${known}`;
  };
  const rows = engines.map((engine) => [
    engineNames[engine] ?? engine,
    cell("wpt", engine),
    cell("test262", engine),
    cell("regressions", engine),
  ]);
  const { wpt, test262 } = result.sources;
  return [
    "## Conformance",
    "",
    `\`vp run test:conformance\`. ${recorded(result)} Passed / failed, with recorded known failures; [conformance](../conformance.md) explains each category.`,
    `WPT ${short(wpt.revision)} (${wpt.selectedFiles} files), Test262 ${short(test262.revision)} (${test262.selectedFiles} files).`,
    `Unexpected results: ${result.verdict.unexpected}.`,
    "",
    ...table(["Engine", "WPT", "Test262", "Regressions"], rows),
  ];
}

function url(): string[] {
  const result = read("url-wpt.json");
  const rows = engines.map((engine) => {
    const counts = result.backends[engine];
    return [
      engineNames[engine] ?? engine,
      `${counts.total - counts.failures} / ${counts.total}`,
      engine === "node-reference" ? "— (Node's parser)" : String(counts.unexpected.length),
    ];
  });
  return [
    "## URL",
    "",
    `\`vp run test:url\`. ${recorded(result)} The WPT data bundled with the \`url\` crate; failures outside its expected list are unexpected.`,
    "",
    ...table(["Engine", "Passed", "Unexpected failures"], rows),
  ];
}

function polyfills(): string[] {
  const result = read("polyfill-matrix.json");
  const rows = Object.entries(
    result.artifacts as Record<string, { bytes: number; polyfills: { api: string }[] }>,
  ).map(([name, artifact]) => [
    name,
    artifact.bytes.toLocaleString("en-US"),
    artifact.polyfills.map((polyfill) => polyfill.api).join(", ") || "none",
  ]);
  return [
    "## Polyfills",
    "",
    `\`vp run test:polyfills\`. ${recorded(result)} ${result.summary.passed} of ${result.summary.passed + result.summary.failed} checks passed. Bundle sizes of the test builds:`,
    "",
    ...table(["Build", "Bytes", "Intl polyfills"], rows),
  ];
}

