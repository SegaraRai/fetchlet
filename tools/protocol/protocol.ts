// Writes the fetchlet-web protocol, defined once in
// crates/fetchlet-web/protocol.json, to the Rust and TypeScript constants
// that the host and the guest compile: `vp run build:protocol`. A change to
// the operations must come with a new version, since a guest built for the
// old operations would otherwise call a host that no longer serves them; the
// written Rust file records the operations' fingerprint for that check. With
// --check it fails instead of writing when either file is stale, which
// `vp run check` runs.

import { createHash } from "node:crypto";
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

import { root } from "@fetchlet-internal/tools-workspace/paths";

const input = resolve(root, "crates/fetchlet-web/protocol.json");
const rustOutput = resolve(root, "crates/fetchlet-web/src/protocol.rs");
const typescriptOutput = resolve(root, "packages/web/src/internal/protocol.ts");
// The line width of rustfmt and of the formatter, so that the written files
// pass `cargo fmt --check` and `vp fmt --check`.
const printWidth = 100;

interface Protocol {
  version: number;
  operations: Record<string, string[]>;
}

const protocol = JSON.parse(readFileSync(input, "utf8")) as Protocol;
if (!Number.isInteger(protocol.version) || protocol.version < 1) {
  fail(`the version in ${input} must be a positive integer`);
}
const seen = new Set<string>();
for (const operation of Object.values(protocol.operations).flat()) {
  if (seen.has(operation)) {
    fail(`${input} lists ${operation} twice`);
  }
  seen.add(operation);
}

/** The operations in a canonical order, so that reordering them is not a change. */
function fingerprint(operations: Record<string, string[]>): string {
  const canonical = Object.keys(operations)
    .sort()
    .map((api) => [api, [...operations[api]!].sort()]);
  return createHash("sha256").update(JSON.stringify(canonical)).digest("hex");
}

const header = [
  "Generated by tools/protocol/protocol.ts from crates/fetchlet-web/protocol.json.",
  "Change that file and run `vp run build:protocol`.",
];
const versionDoc = [
  "The version of the operation names and messages. The guest runtime uses",
  "host implementations only when it was built for the same version.",
];
const operationsDoc = [
  "The operations of each Web API, by the name `web.capabilities` reports;",
  "`web` is always served.",
];
const print = fingerprint(protocol.operations);

function rust(): string {
  const entries = Object.entries(protocol.operations).flatMap(([api, operations]) => {
    const quoted = operations.map((operation) => JSON.stringify(operation));
    const line = `    (${JSON.stringify(api)}, &[${quoted.join(", ")}]),`;
    if (line.length <= printWidth) {
      return [line];
    }
    return [
      "    (",
      `        ${JSON.stringify(api)},`,
      "        &[",
      ...quoted.map((operation) => `            ${operation},`),
      "        ],",
      "    ),",
    ];
  });
  return [
    ...header.map((line) => `// ${line}`),
    `// Operations fingerprint: ${print}`,
    "",
    ...versionDoc.map((line) => `/// ${line}`),
    `pub const PROTOCOL_VERSION: u32 = ${protocol.version};`,
    "",
    ...operationsDoc.map((line) => `/// ${line}`),
    "/// The crate's tests check `dispatch` against it.",
    "#[cfg(test)]",
    "pub(crate) const OPERATIONS: &[(&str, &[&str])] = &[",
    ...entries,
    "];",
    "",
  ].join("\n");
}

function typescript(): string {
  const entries = Object.entries(protocol.operations).flatMap(([api, operations]) => {
    const key = /^[A-Za-z_$][\w$]*$/.test(api) ? api : JSON.stringify(api);
    const quoted = operations.map((operation) => JSON.stringify(operation));
    const line = `  ${key}: [${quoted.join(", ")}],`;
    if (line.length <= printWidth) {
      return [line];
    }
    return [`  ${key}: [`, ...quoted.map((operation) => `    ${operation},`), "  ],"];
  });
  return [
    ...header.map((line) => `// ${line}`),
    "",
    "/**",
    ...versionDoc.map((line) => ` * ${line}`),
    " */",
    `export const PROTOCOL_VERSION = ${protocol.version};`,
    "",
    "/**",
    ...operationsDoc.map((line) => ` * ${line}`),
    " */",
    "export const hostOperations = {",
    ...entries,
    "} as const;",
    "",
  ].join("\n");
}

function committed(path: string): string | undefined {
  return existsSync(path) ? readFileSync(path, "utf8").replaceAll("\r\n", "\n") : undefined;
}

function fail(message: string): never {
  console.error(`[protocol] ${message}`);
  process.exit(1);
}

// The version and fingerprint the committed Rust file was written with.
const previous = committed(rustOutput);
const previousVersion = previous?.match(/PROTOCOL_VERSION: u32 = (\d+);/)?.[1];
const previousPrint = previous?.match(/Operations fingerprint: ([0-9a-f]+)/)?.[1];
if (previousVersion === String(protocol.version) && previousPrint !== print) {
  fail(
    `the operations in ${input} changed but its version is still ${protocol.version}; ` +
      "raise the version so that guests built for the old operations do not call this host",
  );
}

const outputs: [string, string][] = [
  [rustOutput, rust()],
  [typescriptOutput, typescript()],
];
if (process.argv.includes("--check")) {
  for (const [path, text] of outputs) {
    if (committed(path) !== text) {
      fail(`${path} differs from ${input}; run \`vp run build:protocol\``);
    }
  }
} else {
  for (const [path, text] of outputs) {
    writeFileSync(path, text);
  }
}
