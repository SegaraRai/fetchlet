import { defineConfig } from "vite-plus";

// The scripts Rust embeds (src/execution/script.rs) compile from js-src/ into the
// committed js/, which include_str! reads, so building the crate
// needs no JavaScript toolchain. Each output is a classic script in the
// engine's language level: nothing is lowered.
const common = {
  root: "js-src",
  outDir: process.env.FETCHLET_SCRIPTS_OUT_DIR ?? "js",
  platform: "neutral",
  target: "esnext",
  dts: false,
  clean: false,
  tsconfig: "tsconfig.json",
  outputOptions: {
    entryFileNames: "[name].js",
    banner: "// Generated by `vp run build:scripts` from the TypeScript sources in js-src/.",
  },
} as const;

export default defineConfig({
  root: import.meta.dirname,
  run: {
    tasks: {
      build: {
        command: "vp pack",
        cache: false,
      },
    },
  },
  pack: [
    // The bridge's modules share one function scope, so that none of their
    // bindings becomes a global of the script.
    {
      ...common,
      entry: {
        "host-bridge": "js-src/host-bridge/index.ts",
      },
      format: "iife",
    },
    // Likewise for the stack trace API, which QuickJS and Boa evaluate.
    {
      ...common,
      entry: {
        "stack-trace": "js-src/stack-trace.ts",
      },
      format: "iife",
    },
    // Single-file scripts stay at the top level: Rust reads the completion
    // value of the event loop step and of the background settle.
    {
      ...common,
      entry: ["js-src/runtime.ts", "js-src/event-loop.ts", "js-src/background.ts"],
      format: "esm",
    },
  ],
});
