import { defineConfig } from "vite-plus";

// The browser script DevService serves (src/dev/service.rs) compiles from js-src/
// into the committed js/, which include_str! reads, so building the
// crate needs no JavaScript toolchain.
export default defineConfig({
  root: import.meta.dirname,
  run: {
    tasks: {
      build: {
        command: "vp pack",
        cache: false,
      },
    },
  },
  pack: {
    entry: ["js-src/dev-reload.ts"],
    root: "js-src",
    outDir: process.env.FETCHLET_SCRIPTS_OUT_DIR ?? "js",
    format: "esm",
    platform: "browser",
    target: "esnext",
    dts: false,
    clean: false,
    tsconfig: "tsconfig.json",
    outputOptions: {
      entryFileNames: "[name].js",
      banner: "// Generated by `vp run build:scripts` from the TypeScript sources in js-src/.",
    },
  },
});
